func setDXClusterLineLength(t *testing.T, lineLength int) {
	t.Helper()
	prev := CurrentDXClusterLayout()
	if err := SetDXClusterLineLength(lineLength); err != nil {
		t.Fatalf("set line length: %v", err)
	}
	t.Cleanup(func() {
		_ = SetDXClusterLineLength(prev.LineLength)
	})
}

