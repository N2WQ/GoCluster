func f1Asset() OrdinalAsset {
	asset := OrdinalAsset{SchemaVersion: 1, Experimental: true, Mode: "CW", Alphabet: OrdinalAlphabet, Alignment: "unit-suffix-MSDI-v1", ReferenceVersion: "ccv2-reference-v1",
		SNREdges: [7]int{-999, 0, 6, 12, 18, 24, 999}, EmissionPriorTotal: 1, InsertionPriorTotal: 1, GapPriorAlpha: 1, GapPriorBeta: 1,
		Sources: [2]OrdinalTrainingSource{
			{DateUTC: "20261107", SHA256: "2a78ec300acc2cfe29048201af4e971cad933db01c6f36b567ac7443b57ccd34", FocalRows: 458495, AcceptedPairs: 21, FittedCWPairs: 21},
			{DateUTC: "20261114", SHA256: "ad0c8f5a942bab03da052cbe91c2087e59ff566cbd48aa2be8be43b1140bff49", FocalRows: 882021},
		}}
	// Independently supplied rational cell: A opportunities76, A38/B37/del1;
	// one inserted A and 97 stops. This is not generated by the alignment code.
	c := &asset.Cells[2]
	*c = OrdinalEventCell{Pairs: 21, Matches: 38, Substitutions: 37, Deletions: 1, Insertions: 1, SourceCharacters: 76, SubjectCharacters: 76, GapStops: 97}
	c.Opportunities[0], c.Events[0][0], c.Events[0][1], c.Events[0][37], c.InsertionSymbols[0] = 76, 38, 37, 1, 1
	return asset
}

func f1Model(t *testing.T) *OrdinalModel {
	t.Helper()
	a := f1Asset()
	m, err := NewOrdinalModel(&a)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func f1Near(t *testing.T, got, want float64) {
	t.Helper()
	if math.IsNaN(got) || math.IsInf(got, 0) || math.Abs(got-want) > 1e-12 {
		t.Fatalf("got %.17g want %.17g", got, want)
	}
}

func TestCCV2F1PosteriorMeans(t *testing.T) {
	c := f1Model(t).cells[2]
	f1Near(t, math.Exp(c.logEvents[0][0]), 1445.0/2926)
	f1Near(t, math.Exp(c.logEvents[0][1]), 1407.0/2926)
	f1Near(t, math.Exp(c.logEvents[0][37]), 39.0/2926)
	f1Near(t, math.Exp(c.logEvents[0][2]), 1.0/2926)
	var total float64
	for _, p := range c.logEvents[0] {
		total += math.Exp(p)
	}
	f1Near(t, total, 1)
	f1Near(t, math.Exp(c.logInsert[0]), 19.0/37)
	f1Near(t, math.Exp(c.logInsert[1]), 1.0/74)
	f1Near(t, math.Exp(c.logContinue), 1.0/50)
}

func TestCCV2F1AlignedPathScore(t *testing.T) {
	m := f1Model(t)
	for _, tc := range []struct {
		source, observed string
		want             float64
	}{
		{"AA", "A", math.Log(1445.0/2926) + math.Log(39.0/2926) + 3*math.Log(49.0/50)},
		{"A", "AA", math.Log(1445.0/2926) + math.Log(1.0/50) + math.Log(19.0/37) + 2*math.Log(49.0/50)},
		{"A", "A", math.Log(1445.0/2926) + 2*math.Log(49.0/50)},
		{"A", "AAA", math.Log(1445.0/2926) + 2*math.Log(1.0/50) + 2*math.Log(19.0/37) + 2*math.Log(49.0/50)},
	} {
		got, ok := m.Score(tc.source, tc.observed, "CW", 12, true)
		if !ok {
			t.Fatal("literal score unavailable")
		}
		f1Near(t, got, tc.want)
	}
}

func TestCCV2F1AlignmentTieGoldens(t *testing.T) {
	for _, tc := range []struct{ source, observed, events string }{
		{"AA", "A", "MD"}, {"A", "AA", "MI"}, {"AB", "BA", "SS"}, {"ABAB", "BABA", "DMMMI"},
		{"AB", "AXB", "MIM"}, {"AXB", "AB", "MDM"}, {"A", "AXXX", "MIII"}, {"AXXX", "A", "MDDD"},
		{"ABBA", "ABA", "MMDM"}, {"A", "BA", "IM"}, {"AB", "ACB", "MIM"},
	} {
		var events []byte
		walkOrdinalAlignment(tc.source, tc.observed, func(op byte, _, _ int) { events = append(events, op) })
		if string(events) != tc.events {
			t.Fatalf("%s->%s events=%s want=%s", tc.source, tc.observed, events, tc.events)
		}
	}
}

func TestCCV2F1FocalSNRDomain(t *testing.T) {
	for _, tc := range []struct{ value, bin int }{{-1000, -1}, {-999, -1}, {-998, 0}, {0, 0}, {1, 1}, {6, 1}, {7, 2}, {12, 2}, {13, 3}, {18, 3}, {19, 4}, {24, 4}, {25, 5}, {999, 5}, {1000, -1}} {
		if got := ordinalSNRBin("CW", tc.value, true); got != tc.bin {
			t.Fatalf("SNR%d bin=%d want=%d", tc.value, got, tc.bin)
		}
	}
	if ordinalSNRBin("CW", 0, false) != -1 || ordinalSNRBin("RTTY", 12, true) != -1 {
		t.Fatal("unsupported/missing SNR gained a bin")
	}
}

func TestCCV2F1SparseCoverage(t *testing.T) {
	m := f1Model(t)
	if _, ok := m.Score("A", "B", "CW", 12, true); !ok {
		t.Fatal("unseen inserted/observed character wrongly requires source exposure")
	}
	if _, ok := m.Score("B", "A", "CW", 12, true); ok {
		t.Fatal("unexposed candidate source character scored")
	}
	for _, n := range []uint64{49, 50} {
		m.cells[2].opportunities[0] = n
		if _, ok := m.Score("A", "A", "CW", 12, true); ok != (n == 50) {
			t.Fatal("source floor boundary")
		}
	}
	for _, n := range []uint64{49, 50} {
		m.cells[2].gapStops = n
		if _, ok := m.Score("A", "A", "CW", 12, true); ok != (n == 50) {
			t.Fatal("gap floor boundary")
		}
	}
}

func TestCCV2F1WholeDecisionFallback(t *testing.T) {
	m := f1Model(t)
	var proposals []FrequencyProposal
	for n := 1; n <= 8; n++ {
		id := strings.Repeat("A", n)
		proposals = append(proposals, FrequencyProposal{Call: id, Identity: id, Support: n, WeightedSupportMilli: n * 100})
	}
	proposals = append(proposals, FrequencyProposal{Call: "B", Identity: "B", Support: 1})
	ranked, available := m.RankFrequencyProposals(proposals, "A", "CW", 12, true)
	if available || len(ranked) != 9 || ranked[0].Identity != "AAAAAAAA" || ranked[8].Identity != "B" {
		t.Fatalf("partial-score fallback lost geometry: %+v available=%v", ranked, available)
	}
	ranked, available = m.RankFrequencyProposals(proposals[:8], "A", "CW", 12, true)
	if !available || ranked[0].Identity != "A" {
		t.Fatal("reachable scored ranking missing")
	}
	if proposals[0].Identity != "A" {
		t.Fatal("ranking mutated input")
	}
}

func TestCCV2F1RankingOrder(t *testing.T) {
	m := f1Model(t)
	m.cells[2].opportunities[1] = 76
	m.cells[2].logEvents[1][0] = m.cells[2].logEvents[0][0]
	proposals := []FrequencyProposal{{Identity: "B", Support: 2, WeightedSupportMilli: 900}, {Identity: "A", Support: 3, WeightedSupportMilli: 900}}
	ranked, ok := m.RankFrequencyProposals(proposals, "A", "CW", 12, true)
	if !ok || ranked[0].Identity != "A" {
		t.Fatal("score tie lost raw support order")
	}
	proposals[1].Support = 2
	ranked, _ = m.RankFrequencyProposals(proposals, "A", "CW", 12, true)
	if ranked[0].Identity != "A" {
		t.Fatal("score tie lost lexical order")
	}
	proposals[0].WeightedSupportMilli = 1000
	ranked, _ = m.RankFrequencyProposals(proposals, "A", "CW", 12, true)
	if ranked[0].Identity != "B" {
		t.Fatal("score tie lost weight order")
	}
}

func TestCCV2F1AssetCountIntegrity(t *testing.T) {
	for _, mutate := range []func(*OrdinalAsset){
		func(a *OrdinalAsset) { a.Experimental = false }, func(a *OrdinalAsset) { a.EmissionPriorTotal = 38 },
		func(a *OrdinalAsset) { a.Cells[2].Opportunities[0]++ }, func(a *OrdinalAsset) { a.Cells[2].Insertions++ },
		func(a *OrdinalAsset) { a.Cells[2].GapStops++ }, func(a *OrdinalAsset) { a.Cells[2].Pairs++ },
		func(a *OrdinalAsset) { a.Cells[2].ExactPairs = a.Cells[2].Pairs },
		func(a *OrdinalAsset) { a.Cells[2].Events[0][0] = math.MaxUint64 }, func(a *OrdinalAsset) { a.Sources[0].SHA256 = "tampered" },
	} {
		a := f1Asset()
		mutate(&a)
		if _, err := NewOrdinalModel(&a); err == nil {
			t.Fatal("invalid asset accepted")
		}
	}
}

func TestCCV2F1BoundsAndImmutability(t *testing.T) {
	a := f1Asset()
	m, err := NewOrdinalModel(&a)
	if err != nil {
		t.Fatal(err)
	}
	before, _ := m.Score("A", "A", "CW", 12, true)
	a.Cells[2] = OrdinalEventCell{}
	a.Alphabet = "changed"
	for _, call := range []string{"", strings.Repeat("A", 33), "A?", "Á"} {
		if _, ok := m.Score(call, "A", "CW", 12, true); ok {
			t.Fatal("out-of-domain candidate scored")
		}
	}
	if _, ok := m.Score(strings.Repeat("A", 32), "A", "CW", 12, true); !ok {
		t.Fatal("32-symbol boundary rejected")
	}
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Go(func() {
			for j := 0; j < 100; j++ {
				got, ok := m.Score("A", "A", "CW", 12, true)
				if !ok || got != before {
					t.Error("immutable score changed")
				}
			}
		})
	}
	wg.Wait()
	got, _ := m.Score("A", "A", "CW", 12, true)
	if !reflect.DeepEqual(got, before) {
		t.Fatal("DTO mutation changed model")
	}
}
