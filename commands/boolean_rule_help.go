package commands

import (
	"fmt"
	"strings"

	"dxcluster/filter"
	"dxcluster/filter/expr"
	"dxcluster/spot"
)

// BooleanRuleHelpLines is the canonical reference shared by HELP RULE renderers.
// Keep literal expression examples byte-exact when presenting these lines.
func BooleanRuleHelpLines() []string {
	lines := make([]string, 0, 90)
	lines = append(lines,
		"GO and CC use the same rule syntax.",
		"",
		"Commands:",
		"PASS RULE <0..9> <expression>",
		"REJECT RULE <0..9> <expression>",
		"RESET FILTER RULE <0..9|ALL>",
		"RESET FILTER",
		"SHOW FILTER | SHOW FILTER RULE | SHOW FILTER FULL",
		"HELP RULE",
		"",
		"Editing and resetting:",
		"Each slot holds one action and expression.",
		"Editing a slot replaces both.",
		"RESET FILTER RULE clears only the selected slots.",
		"RESET FILTER clears all personal rules.",
		"It also turns NEARBY OFF.",
		"Neither reset changes other controls or profile settings.",
		"",
		"Starting rules:",
		"New accounts get default modes and sources in editable PASS rule 0.",
		"Users moving from old filters get this rule too.",
		"They keep their settings.",
		"Existing Boolean rules stay unchanged.",
		"RESET FILTER does not reinstall that rule.",
		"",
		"How rules combine:",
		"PASS allows matching spots.",
		"REJECT blocks matching spots.",
		"Matching any PASS is enough.",
		"REJECT wins over PASS.",
		"Slot IDs are not priorities.",
		"Adding PASS broadens selection.",
		"To narrow defaults, edit or remove slot 0.",
		"Without PASS rules, only REJECT rules restrict selection.",
		"No rules means no personal restriction.",
		"Separate controls still apply.",
		"",
		"Report sources:",
		"PASS without SOURCE allows humans and skimmers.",
		"Add AND SOURCE=HUMAN to select human reports only.",
		"SOURCE follows the same Boolean logic as other fields.",
		"SOURCE=HUMAN,SKIMMER allows both report sources.",
		"SOURCE does not change feed connections.",
		"",
		"Writing expressions:",
		"Combine comparisons with NOT, AND, OR and parentheses.",
		"The order is NOT then AND then OR.",
		"Parentheses change that order.",
		"Use one value, comma lists or [comma,lists].",
		"= matches any listed value.",
		"<> excludes all listed values.",
		"ALL, ON and OFF are not wildcard values.",
		"< <= > >= take one value, only for FREQ, SNR, DXZONE and DEZONE.",
		"FREQ uses kHz.",
		"Numbers must be finite and at least zero.",
		"With = or <>, low-high ranges include both endpoints.",
		"SNR takes whole numbers.",
		"Zones take whole numbers from 1 to 40.",
		"",
		"Text and comments:",
		`Double-quote values that contain spaces or punctuation.`,
		`Inside quotes, write "" for a literal ".`,
		"Backslash is not an escape.",
		`COMMENT="CQ ""DX""  !;=()[]"`,
		"COMMENT preserves literal case, punctuation and spaces.",
		"Phrases match anywhere in a comment.",
		"Matching ignores ASCII letter case.",
		"Regex, glob and whole-word matching are not supported.",
		"Each phrase takes 1..64 printable ASCII bytes.",
		"A phrase cannot be all spaces.",
		"",
		"Missing values and special cases:",
		"A missing or unknown value makes every comparison false, including <>.",
		"NOT flips that false to true.",
		"MODE UNKNOWN selects blank modes.",
		"EVENT NONE selects eventless spots.",
		"PATH INSUFFICIENT is an explicit class, not a missing value.",
		"CONF is unknown for exempt modes.",
		"Expressions do not bypass those modes.",
		"PATH classes are exact.",
		"UNLIKELY does not include CLOSED.",
		"SNR comparisons apply to any present report, including human spots.",
		"Include SOURCE=SKIMMER to keep the old MINSNR human exemption.",
		"",
		"NEARBY and separate controls:",
		"NEARBY ON skips geography checks.",
		"Saved rules stay unchanged.",
		"Emptied rules are ignored.",
		"Other conditions still apply.",
		"BAND, MODE, calls, FREQ, SNR, SOURCE, EVENT, COMMENT, CONF and PATH are not geography.",
		"Rule edits need no usable grid.",
		"Geometry may remain unavailable.",
		"NEARBY and SELF/BEACON/TOXIC/WWV/WCY/ANNOUNCE/PC93 remain separate controls.",
		"SELF ON can bypass personal rules and NEARBY.",
		"TOXIC still applies.",
		"Use the control commands, not rule fields.",
		"",
		"Fields and values:",
		"Fields: "+strings.Join(filter.SupportedRuleFields(), " "),
		"DXCALL/DECALL accept exact calls or one * at either end, including * alone.",
		"DXDXCC/DEDXCC take positive ADIF codes or exact CTY canonical labels.",
		"Labels need CTY and are saved/read back as numeric ADIF codes.",
		"DXDXCC<>K becomes DXDXCC<>291; labels select the whole entity.",
		"Unknown or conflicting labels reject the entire edit.",
		"DXGRID2/DEGRID2 take two letters AA..RR.",
		"Outside COMMENT, values are case-insensitive and normalized.",
		"Use CONF, not CONFIDENCE.",
		"DX is the station being spotted.",
		"DE is the spotter.",
		"DXSTATE/DESTATE use US/Canadian registered mailing codes.",
		"Missing values are unknown.",
		"",
		"Examples:",
		"PASS RULE 0 MODE=CW,FT8 AND SOURCE=HUMAN",
		"REJECT RULE 9 SNR<-15 OR COMMENT=\"test beacon\"",
		"PASS RULE 2 NOT (DXCONT=EU OR BAND=20M)",
		"PASS RULE 0 MODE=CW AND DXDXCC<>K",
		"",
		"Limits:",
		fmt.Sprintf("%d slots.", filter.MaxRuleSlots),
		fmt.Sprintf("%d bytes per expression, both raw and canonical.", expr.MaxBytes),
		fmt.Sprintf("Per rule: %d comparisons, %d nodes, nesting depth %d.",
			expr.MaxAtoms, expr.MaxNodes, expr.MaxDepth),
		fmt.Sprintf("%d values per comparison.", expr.MaxValuesPerAtom),
		fmt.Sprintf("All rules combined: %d comparisons and %d values.",
			filter.MaxTotalRuleAtoms, filter.MaxTotalRuleValues),
		"Commands must fit the node's command-line byte limit.",
		"Use YAML schema 5 for longer expressions.",
		"Old category commands and CC filter/mode shortcuts are not translated.",
		"Use numbered rules instead.",
		"RESET RULE and SET DX FILTER are not aliases.",
		"",
		"Supported values:",
	)
	for _, vocabulary := range []struct {
		name   string
		values []string
	}{
		{"BAND", spot.SupportedBandNames()}, {"MODE", filter.SupportedModes()},
		{"SOURCE", filter.SupportedSources}, {"EVENT", append(filter.SupportedEvents(), "NONE")},
		{"DX/DECONT", filter.SupportedContinents}, {"DX/DESTATE", spot.StateCodes()},
		{"CONF", filter.SupportedConfidenceSymbols}, {"PATH", filter.SupportedPathClasses},
	} {
		lines = append(lines, vocabulary.name+": "+strings.Join(vocabulary.values, ", "))
	}
	return lines
}
