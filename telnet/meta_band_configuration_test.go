func metaBandMachineFixture(t *testing.T) filter.V7Configuration {
	t.Helper()
	cfg, _ := v7PreparedFixture(t)
	var err error
	cfg.Filters.CC, err = cfg.Filters.CC.WithDXBM(filter.CCPass, []string{"UHF"})
	if err != nil || len(cfg.Filters.CC.DXBM.FrequencyOverrides) == 0 {
		t.Fatalf("feature fixture: %v", err)
	}
	cfg, _, _, err = filter.PrepareV7Configuration(cfg)
	if err != nil {
		t.Fatal(err)
	}
	return cfg
}

func TestMetaBandMachineCompleteExportRestore(t *testing.T) {
	cfg := metaBandMachineFixture(t)
	_, rules := v7PreparedFixture(t)
	for _, active := range []string{"go", "cc"} {
		status := configurationReadbackStatus{Effective: readbackEffectiveStatus{Dialect: active}}
		response, err := renderV7YAMLReadback(cfg, rules, status, map[string]readbackPresetStatus{"go": {}, "cc": {}}, "CONFIG", "meta-1", "revision-1")
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(response, "frequency_overrides:") {
			t.Fatal("complete export omitted feature")
		}
		var document struct {
			Configuration yaml.Node `yaml:"configuration"`
		}
		if err := yaml.Unmarshal([]byte(response), &document); err != nil {
			t.Fatal(err)
		}
		encoded, err := yaml.Marshal(&document.Configuration)
		if err != nil {
			t.Fatal(err)
		}
		for _, verb := range []string{"PUT", "VALIDATE"} {
			request, err := decodeV7MachineRequest(v7MachineRequestFixture(string(encoded), verb == "PUT"), machineCommand{Verb: verb, Resource: "CONFIG", SchemaVersion: 7}, nil)
			if err != nil {
				t.Fatal(err)
			}
			before := cfg.Clone()
			before.Filters.CC.DXBM.FrequencyOverrides = nil
			saved := before.Clone()
			restored, err := request.apply(before, active)
			if err != nil {
				t.Fatal(err)
			}
			restored, _, _, err = filter.PrepareV7Configuration(restored)
			if err != nil || !restored.Equal(cfg) || restored.Fingerprint() != cfg.Fingerprint() || !before.Equal(saved) {
				t.Fatalf("%s/%s feature restore changed state: %v", active, verb, err)
			}
		}
	}
}

func TestMetaBandMachineOverrideValidation(t *testing.T) {
	before := metaBandMachineFixture(t)
	var id string
	for key := range before.Filters.CC.DXBM.FrequencyOverrides {
		id = key
		break
	}
	valid := fmt.Sprintf("{%q: true}", id)
	var oversized strings.Builder
	oversized.WriteString("{")
	for _, cell := range filter.CCSupportedFrequencyCells() {
		fmt.Fprintf(&oversized, "%q: true,", cell.ID)
	}
	oversized.WriteString("'UNKNOWN': true}")
	for _, test := range []struct {
		name, overrides string
		valid           bool
	}{
		{"valid", valid, true}, {"empty", "{}", true}, {"null", "null", false}, {"sequence", "[]", false}, {"unknown", "{'P:123456789': true}", false},
		{"wrong-bool", fmt.Sprintf("{%q: 'true'}", id), false}, {"duplicate", fmt.Sprintf("{%q: true, %q: false}", id, id), false},
		{"duplicate-case", fmt.Sprintf("{%q: true, %q: false}", id, strings.ToLower(id)), false}, {"oversized", oversized.String(), false},
	} {
		t.Run(test.name, func(t *testing.T) {
			body := "dialect: cc\nfilters:\n  dxbm:\n    active: true\n    base_allow: false\n    slots: {}\n    frequency_overrides: " + test.overrides + "\n"
			saved := before.Clone()
			request, err := decodeV7MachineRequest(v7MachineRequestFixture(body, true), machineCommand{Verb: "PATCH", Resource: "FILTER", SchemaVersion: 7}, nil)
			if err == nil {
				var result filter.V7Configuration
				result, err = request.apply(before, "cc")
				if err == nil {
					_, _, _, err = filter.PrepareV7Configuration(result)
				}
			}
			if (err == nil) != test.valid {
				t.Fatalf("valid=%v, err=%v", test.valid, err)
			}
			if !before.Equal(saved) {
				t.Fatal("decoding/admission mutated prior state")
			}
		})
	}
	// Inactive DXBM may not retain dormant feature exceptions.
	body := "dialect: cc\nfilters:\n  dxbm:\n    active: false\n    base_allow: true\n    slots: {}\n    frequency_overrides: " + valid + "\n"
	if _, err := decodeV7MachineRequest(v7MachineRequestFixture(body, true), machineCommand{Verb: "PATCH", Resource: "FILTER", SchemaVersion: 7}, nil); err == nil {
		t.Fatal("inactive DXBM accepted frequency exceptions")
	}
}

func TestMetaBandHumanReadbackShowsEffectiveExceptions(t *testing.T) {
	cfg := metaBandMachineFixture(t)
	for _, enabled := range []bool{true, false} {
		selection := cfg.Filters.CC.DXBM
		selection.BaseAllow = !enabled
		selection.FrequencyOverrides = make(filter.CCFrequencyOverrides)
		// Fixed independently stated boundary point and interval: no expected
		// range label is generated by the formatter being tested.
		selection.FrequencyOverrides["P:420000"] = enabled
		selection.FrequencyOverrides["I:420000:450000"] = enabled
		response, err := renderNativeCCBody(maxV7YAMLBytes, func(h *humanResponse) error { return writeNativeCCDXBM(h, selection) })
		if err != nil {
			t.Fatal(err)
		}
		want := "ALLOW"
		if !enabled {
			want = "BLOCK"
		}
		for _, line := range []string{"Additional band selections:", "f = 420000:", "420000 < f < 450000:"} {
			if !strings.Contains(response, line) {
				t.Fatalf("missing %q in %q", line, response)
			}
		}
		for _, line := range strings.Split(response, "\n") {
			if strings.Contains(line, "f = 420000:") || strings.Contains(line, "420000 < f < 450000:") {
				if !strings.Contains(line, want) {
					t.Fatalf("readback exception has wrong selection: %q", line)
				}
			}
		}
	}
}
